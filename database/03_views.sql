CREATE OR REPLACE VIEW VW_ORCAMENTOS_COMPLETOS AS
SELECT O.ID_ORCAMENTO, O.ID_CLIENTE, C.NOME AS NOME_CLIENTE, C.CPF,
       O.ID_VEICULO, V.MARCA AS MARCA_VEICULO, V.MODELO AS MODELO_VEICULO,
       V.PLACA, O.ID_USUARIO, U.NOME AS RESPONSAVEL,
       O.DATA_ORCAMENTO, O.VALIDADE, O.STATUS, O.VALOR_TOTAL, O.OBSERVACAO
FROM ORCAMENTO O
JOIN CLIENTE C ON C.ID_CLIENTE = O.ID_CLIENTE
JOIN VEICULO V ON V.ID_VEICULO = O.ID_VEICULO
              AND V.ID_CLIENTE = O.ID_CLIENTE
JOIN USUARIO U ON U.ID_USUARIO = O.ID_USUARIO;

CREATE OR REPLACE VIEW VW_ITENS_ORCAMENTO AS
SELECT I.ID_ITEM, I.ID_ORCAMENTO, I.ID_PRODUTO,
       P.CODIGO AS CODIGO_PRODUTO, P.NOME AS PRODUTO,
       I.QUANTIDADE, I.VALOR_UNITARIO, I.SUBTOTAL
FROM ITEM_ORCAMENTO I
JOIN PRODUTO P ON P.ID_PRODUTO = I.ID_PRODUTO;

-- Usa o minimo especifico de cada produto, nao um limite generico de 10.
CREATE OR REPLACE VIEW VW_ESTOQUE_BAIXO AS
SELECT P.ID_PRODUTO, P.CODIGO, P.NOME AS PRODUTO,
       C.NOME AS CATEGORIA, M.NOME AS MARCA,
       E.QUANTIDADE, P.ESTOQUE_MINIMO, E.DATA_ATUALIZACAO
FROM ESTOQUE E
JOIN PRODUTO P ON P.ID_PRODUTO = E.ID_PRODUTO
JOIN CATEGORIA C ON C.ID_CATEGORIA = P.ID_CATEGORIA
JOIN MARCA M ON M.ID_MARCA = P.ID_MARCA
WHERE E.QUANTIDADE <= P.ESTOQUE_MINIMO;

