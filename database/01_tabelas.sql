-- AutoMax-Pecas | Oracle FreeSQL | Estrutura de 9 tabelas
-- Fonte: DDL documentado no relatorio do projeto e migracao original.
-- Executar APENAS em schema novo e vazio, nunca sobre o banco em producao.
-- Ordem de criacao respeita as dependencias entre chaves estrangeiras.
-- Nenhum dado de clientes, contas ou senhas e incluido aqui.

-- 1. CLIENTE

CREATE TABLE CLIENTE (
    ID_CLIENTE NUMBER,
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    TELEFONE VARCHAR2(20),
    EMAIL VARCHAR2(100),
    ENDERECO VARCHAR2(200),

    CONSTRAINT PK_CLIENTE
        PRIMARY KEY (ID_CLIENTE),

    CONSTRAINT UK_CLIENTE_CPF
        UNIQUE (CPF)
);




-- 2. CATEGORIA

CREATE TABLE CATEGORIA (
    ID_CATEGORIA NUMBER,
    NOME VARCHAR2(60) NOT NULL,
    DESCRICAO VARCHAR2(200),

    CONSTRAINT PK_CATEGORIA
        PRIMARY KEY (ID_CATEGORIA),

    CONSTRAINT UK_CATEGORIA_NOME
        UNIQUE (NOME)
);

-- 3. MARCA

CREATE TABLE MARCA (
    ID_MARCA NUMBER,
    NOME VARCHAR2(80) NOT NULL,
    PAIS_ORIGEM VARCHAR2(50),

    CONSTRAINT PK_MARCA
        PRIMARY KEY (ID_MARCA),

    CONSTRAINT UK_MARCA_NOME
        UNIQUE (NOME)
);

-- 4. VEÍCULO

CREATE TABLE VEICULO (
    ID_VEICULO NUMBER,
    ID_CLIENTE NUMBER NOT NULL,
    MARCA VARCHAR2(50) NOT NULL,
    MODELO VARCHAR2(80) NOT NULL,
    ANO NUMBER(4),
    PLACA VARCHAR2(8),

    CONSTRAINT PK_VEICULO
        PRIMARY KEY (ID_VEICULO),

    CONSTRAINT FK_VEICULO_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE (ID_CLIENTE),

    CONSTRAINT UK_VEICULO_PLACA
        UNIQUE (PLACA),

    CONSTRAINT UK_AUTOMAX_VEIC
        UNIQUE (ID_VEICULO, ID_CLIENTE)
);
-- 5. PRODUTO

CREATE TABLE PRODUTO (
    ID_PRODUTO NUMBER,
    ID_CATEGORIA NUMBER NOT NULL,
    ID_MARCA NUMBER NOT NULL,
    CODIGO VARCHAR2(30) NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(300),
    PRECO NUMBER(10,2) NOT NULL,
    ESTOQUE_MINIMO NUMBER NOT NULL,

    CONSTRAINT PK_PRODUTO
        PRIMARY KEY (ID_PRODUTO),

    CONSTRAINT UK_PRODUTO_CODIGO
        UNIQUE (CODIGO),

    CONSTRAINT FK_PRODUTO_CAT
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA (ID_CATEGORIA),

    CONSTRAINT FK_PRODUTO_MAR
        FOREIGN KEY (ID_MARCA)
        REFERENCES MARCA (ID_MARCA),

    CONSTRAINT CK_PRODUTO_PRECO
        CHECK (PRECO >= 0),

    CONSTRAINT CK_PRODUTO_ESTQ
        CHECK (ESTOQUE_MINIMO >= 0)
);

-- 6. ESTOQUE

CREATE TABLE ESTOQUE (
    ID_ESTOQUE NUMBER PRIMARY KEY,
    ID_PRODUTO NUMBER NOT NULL UNIQUE,
    QUANTIDADE NUMBER(10) NOT NULL,
    DATA_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_AUTOMAX_ESTOQUE_PRODUTO
        FOREIGN KEY (ID_PRODUTO)
        REFERENCES PRODUTO (ID_PRODUTO),

    CONSTRAINT CK_AUTOMAX_ESTOQUE_QTD
        CHECK (QUANTIDADE >= 0)
);

-- 7. USUÁRIO

CREATE TABLE USUARIO (
    ID_USUARIO NUMBER PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,

    CONSTRAINT UK_AUTOMAX_USUARIO_EMAIL
        UNIQUE (EMAIL),

    CONSTRAINT CK_AUTOMAX_USUARIO_TIPO
        CHECK (TIPO IN ('ADMIN', 'VENDEDOR', 'GERENTE')),

    CONSTRAINT CK_AUTOMAX_USUARIO_ATIVO
        CHECK (ATIVO IN ('S', 'N'))
);


-- 8. ORÇAMENTO

CREATE TABLE ORCAMENTO (
    ID_ORCAMENTO NUMBER PRIMARY KEY,
    ID_CLIENTE NUMBER NOT NULL,
    ID_VEICULO NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    DATA_ORCAMENTO DATE DEFAULT SYSDATE NOT NULL,
    VALIDADE DATE,
    STATUS VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    VALOR_TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    OBSERVACAO VARCHAR2(500),

    CONSTRAINT FK_AUTOMAX_ORC_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE (ID_CLIENTE),

    CONSTRAINT FK_AUTOMAX_ORC_VEICULO_CLIENTE
        FOREIGN KEY (ID_VEICULO, ID_CLIENTE)
        REFERENCES VEICULO (ID_VEICULO, ID_CLIENTE),

    CONSTRAINT FK_AUTOMAX_ORC_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),

    CONSTRAINT CK_AUTOMAX_ORC_STATUS
        CHECK (
            STATUS IN (
                'PENDENTE',
                'APROVADO',
                'RECUSADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT CK_AUTOMAX_ORC_TOTAL
        CHECK (VALOR_TOTAL >= 0),

    CONSTRAINT CK_AUTOMAX_ORC_VALIDADE
        CHECK (
            VALIDADE IS NULL
            OR TRUNC(VALIDADE) >= TRUNC(DATA_ORCAMENTO)
        )
);






-- 9. ITEM ORÇAMENTO

CREATE TABLE ITEM_ORCAMENTO (
    ID_ITEM NUMBER PRIMARY KEY,
    ID_ORCAMENTO NUMBER NOT NULL,
    ID_PRODUTO NUMBER NOT NULL,
    QUANTIDADE NUMBER(10) NOT NULL,
    VALOR_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,

    CONSTRAINT FK_AUTOMAX_ITEM_ORC
        FOREIGN KEY (ID_ORCAMENTO)
        REFERENCES ORCAMENTO (ID_ORCAMENTO),

    CONSTRAINT FK_AUTOMAX_ITEM_PROD
        FOREIGN KEY (ID_PRODUTO)
        REFERENCES PRODUTO (ID_PRODUTO),

    CONSTRAINT CK_AUTOMAX_ITEM_QTD
        CHECK (QUANTIDADE > 0),

    CONSTRAINT CK_AUTOMAX_ITEM_UNIT
        CHECK (VALOR_UNITARIO >= 0),

    CONSTRAINT CK_AUTOMAX_ITEM_SUBTOTAL
        CHECK (SUBTOTAL >= 0)
);
