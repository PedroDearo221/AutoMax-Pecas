-- AutoMax-Pecas | Consultas SOMENTE LEITURA para verificacao.
-- Execute cada bloco no Oracle FreeSQL, conforme permitido pela interface.

-- As nove tabelas esperadas
SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('CLIENTE','VEICULO','CATEGORIA','MARCA','PRODUTO',
                     'ESTOQUE','USUARIO','ORCAMENTO','ITEM_ORCAMENTO')
ORDER BY TABLE_NAME;

-- As sete sequences esperadas
SELECT SEQUENCE_NAME FROM USER_SEQUENCES
WHERE SEQUENCE_NAME LIKE 'SEQ_AUTOMAX_%'
ORDER BY SEQUENCE_NAME;

-- As tres views esperadas
SELECT VIEW_NAME FROM USER_VIEWS
WHERE VIEW_NAME IN ('VW_ORCAMENTOS_COMPLETOS','VW_ITENS_ORCAMENTO','VW_ESTOQUE_BAIXO')
ORDER BY VIEW_NAME;

-- As cinco triggers e seus estados
SELECT TRIGGER_NAME, STATUS FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN ('TRG_AUTOMAX_ESTOQUE_DATA','TRG_CALCULAR_SUBTOTAL',
                       'TRG_TOTAL_INSERT','TRG_TOTAL_UPDATE','TRG_TOTAL_DELETE')
ORDER BY TRIGGER_NAME;

-- Listagem nao sensivel, evita dados pessoais e senhas.
SELECT ID_PRODUTO, CODIGO, NOME, PRECO, ESTOQUE_MINIMO FROM PRODUTO
ORDER BY ID_PRODUTO;
