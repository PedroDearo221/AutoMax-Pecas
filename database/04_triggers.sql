CREATE OR REPLACE TRIGGER TRG_AUTOMAX_ESTOQUE_DATA
BEFORE INSERT OR UPDATE OF QUANTIDADE ON ESTOQUE
FOR EACH ROW
BEGIN
    :NEW.DATA_ATUALIZACAO := SYSDATE;
END;
/

CREATE OR REPLACE TRIGGER TRG_CALCULAR_SUBTOTAL
BEFORE INSERT OR UPDATE ON ITEM_ORCAMENTO
FOR EACH ROW
BEGIN
    :NEW.SUBTOTAL := :NEW.QUANTIDADE * :NEW.VALOR_UNITARIO;
END;
/

CREATE OR REPLACE TRIGGER TRG_TOTAL_INSERT
AFTER INSERT ON ITEM_ORCAMENTO
FOR EACH ROW
BEGIN
    UPDATE ORCAMENTO
       SET VALOR_TOTAL = VALOR_TOTAL + :NEW.SUBTOTAL
     WHERE ID_ORCAMENTO = :NEW.ID_ORCAMENTO;
END;
/

CREATE OR REPLACE TRIGGER TRG_TOTAL_UPDATE
AFTER UPDATE ON ITEM_ORCAMENTO
FOR EACH ROW
BEGIN
    IF :OLD.ID_ORCAMENTO = :NEW.ID_ORCAMENTO THEN
        UPDATE ORCAMENTO
           SET VALOR_TOTAL = VALOR_TOTAL + :NEW.SUBTOTAL - :OLD.SUBTOTAL
         WHERE ID_ORCAMENTO = :NEW.ID_ORCAMENTO;
    ELSE
        UPDATE ORCAMENTO
           SET VALOR_TOTAL = VALOR_TOTAL - :OLD.SUBTOTAL
         WHERE ID_ORCAMENTO = :OLD.ID_ORCAMENTO;
        UPDATE ORCAMENTO
           SET VALOR_TOTAL = VALOR_TOTAL + :NEW.SUBTOTAL
         WHERE ID_ORCAMENTO = :NEW.ID_ORCAMENTO;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_TOTAL_DELETE
AFTER DELETE ON ITEM_ORCAMENTO
FOR EACH ROW
BEGIN
    UPDATE ORCAMENTO
       SET VALOR_TOTAL = VALOR_TOTAL - :OLD.SUBTOTAL
     WHERE ID_ORCAMENTO = :OLD.ID_ORCAMENTO;
END;
/

